<?php
// passes/success.php — shown after successful Stripe payment for a pass.
header('Cache-Control: no-store, no-cache, must-revalidate, max-age=0');
require_once __DIR__ . '/../config.php';
require_once __DIR__ . '/../includes/stripe.php';

$pageTitle = 'Your Pass is Ready — Bat Cave Road Farm';
$pageCSS   = 'https://batcaveroadfarm.com/css/min.passes.css';
$pageJS    = ['https://batcaveroadfarm.com/js/qrcode.min.js',
              'https://batcaveroadfarm.com/js/min.passes.js'];

require '../includes/head.php';
include '../includes/header.php';

$token = trim((string)($_GET['token'] ?? ''));
$pass  = null; $pt = null;

if ($token !== '') {
    try {
        $st = $pdo->prepare("SELECT p.*, t.label, t.max_guests, t.perks FROM passes p
                              JOIN pass_types t ON t.id = p.pass_type_id
                              WHERE p.token = ? LIMIT 1");
        $st->execute([$token]);
        $row = $st->fetch(PDO::FETCH_ASSOC) ?: null;
        if ($row) { $pass = $row; }
    } catch (Throwable $e) {}
}

// Race: webhook may not have fired yet — check Stripe directly
if ($pass && $pass['status'] === 'pending_payment' && !empty($pass['payment_reference'])) {
    try {
        $session = stripe_retrieve_session((string)$pass['payment_reference']);
        if (($session['payment_status'] ?? '') === 'paid') {
            $pdo->prepare("UPDATE passes SET payment_status='paid', status='active',
                           valid_from=CURDATE(), valid_until=DATE_ADD(CURDATE(), INTERVAL 1 YEAR),
                           payment_provider='stripe' WHERE id=? AND status='pending_payment'")
                ->execute([(int)$pass['id']]);
            $pass['status'] = 'active';
            $pass['valid_from']  = date('Y-m-d');
            $pass['valid_until'] = date('Y-m-d', strtotime('+1 year'));
        }
    } catch (Throwable $e) {}
}

$verifyUrl = 'https://batcaveroadfarm.com/passes/verify.php?token=' . rawurlencode($token);
$active = $pass && $pass['status'] === 'active';
?>

<div class="pass-success-wrap">
    <?php if (!$pass): ?>
    <div class="pass-success-card">
        <div style="font-size:3rem">🌾</div>
        <h1>Pass not found</h1>
        <p style="font-family:'Lora',serif;color:#5c3317">We couldn't find your pass. Call us at (828) 216-5488 and we'll sort it out.</p>
    </div>
    <?php elseif ($active): ?>
    <div class="pass-success-card">
        <div style="font-size:3rem">🎉</div>
        <h1>Your pass is active!</h1>
        <p style="font-family:'Lora',serif;color:#5c3317;margin:0 0 14px">
            <strong><?= htmlspecialchars($pass['holder_name']) ?></strong> —
            <?= htmlspecialchars($pass['label']) ?>
        </p>
        <p style="font-family:'Lora',serif;font-size:.85rem;color:#8b5c2a;margin:0 0 18px">
            Valid until <strong><?= date('F j, Y', strtotime($pass['valid_until'])) ?></strong>
        </p>

        <!-- QR code (generated by min.passes.js using self-hosted qrcode.min.js) -->
        <div id="pass-qr" data-url="<?= htmlspecialchars($verifyUrl, ENT_QUOTES) ?>"></div>

        <p style="font-family:'Lora',serif;font-size:.82rem;color:#8b5c2a;margin:12px 0 8px">
            📱 <strong>Save this QR or bookmark the link below</strong> — show it to staff at the gate.
        </p>
        <div class="pass-link-box"><?= htmlspecialchars($verifyUrl) ?></div>
        <p style="font-family:'Lora',serif;font-size:.8rem;color:#8b5c2a;margin:8px 0 18px;line-height:1.5">
            We've sent a confirmation email to <strong><?= htmlspecialchars($pass['email']) ?></strong> with this link.
            Add this page to your phone's home screen for instant access.
        </p>
        <a class="cta-btn" href="/petting-zoo/">Plan your first visit →</a>
    </div>
    <?php else: ?>
    <div class="pass-success-card">
        <div style="font-size:3rem">⏳</div>
        <h1>Almost there!</h1>
        <p style="font-family:'Lora',serif;color:#5c3317">
            We're confirming your payment — usually takes just a moment.
            Check your email at <strong><?= htmlspecialchars($pass['email'] ?? '') ?></strong>
            for your pass link once it's confirmed.
        </p>
        <p style="font-family:'Lora',serif;font-size:.85rem;color:#8b5c2a;margin-top:12px">
            If you don't hear from us within 15 minutes please call (828) 216-5488.
        </p>
    </div>
    <?php endif; ?>
</div>

<?php require '../includes/footer.php'; ?>
